def risk_for(field: str, current: str, scope: str, category: str = "") -> str:
    if scope == "static_js_html":
        if "production" in category or "translation" in category or len(current) >= 80:
            return "high"
        return "medium"
    if field in {
        "name",
        "title",
        "charaName",
        "cardName",
        "pieceName",
        "parameter",
        "kana",
        "school",
        "outline",
        "description",
        "message",
    }:
        return "high"
    if field in {"shortDescription", "areaDetailName"}:
        return "medium"
    return "low"


def issue_for(field: str, current: str) -> str:
    if field in {"name", "title", "charaName", "cardName", "pieceName", "parameter", "kana", "school"}:
        return "unverified_llm_or_other_proper_name"
    if field in {"description", "outline", "message"} or len(current) >= 80:
        return "unverified_llm_or_other_narrative"
    return "unverified_llm_or_other_structured_or_short_text"


def build_checklist_overlays(dicts: Dictionaries) -> tuple[dict[tuple[str, str, str], dict[str, str]], list[dict[str, str]]]:
    overlays: dict[tuple[str, str, str], dict[str, str]] = {}
    static_rows: list[dict[str, str]] = []
    for row in read_tsv(RELEASE_CHECKLIST):
        if Path(row["file"]).suffix.lower() != ".json":
            static_rows.append(row)
            continue
        target = dicts.checklist_target(row)
        if target:
            overlays[target] = row
    return overlays, static_rows


