def json_scalar(text: str) -> Any:
    if not text:
        return ""
    try:
        return json.loads(text)
    except Exception:
        return text


def stable_key(base: str, obj: dict[str, Any]) -> str:
    if base == "charaMessageList":
        return f"{obj.get('charaNo', '')}|{obj.get('messageId', '')}"
    if base == "live2dList":
        return f"{obj.get('charaId', '')}|{obj.get('live2dId', '')}"
    if base == "eventStoryList":
        value = obj.get("storyIds", "")
        return json.dumps(value, ensure_ascii=False, separators=(",", ":")) if isinstance(value, list) else str(value)
    for field in LIST_KEYS.get(base, ()):
        if field in obj:
            return str(obj[field])
    return ""


class Dictionaries:
    def __init__(self, folder: Path):
        self.folder = folder
        self.data: dict[str, Any] = {}
        self.index: dict[str, dict[str, dict[str, Any]]] = {}

    def load(self, filename: str) -> Any:
        if filename not in self.data:
            self.data[filename] = json.loads(
                (self.folder / filename).read_text(encoding="utf-8-sig")
            )
        return self.data[filename]

    def indexed(self, filename: str) -> dict[str, dict[str, Any]]:
        if filename in self.index:
            return self.index[filename]
        data = self.load(filename)
        if isinstance(data, dict):
            result = {str(k): v for k, v in data.items() if isinstance(v, dict)}
        else:
            base = Path(filename).stem
            result = {}
            for item in data:
                if isinstance(item, dict):
                    result[stable_key(base, item)] = item
        self.index[filename] = result
        return result

    def value(self, filename: str, key: str, field: str, fallback: str = "") -> str:
        obj = self.indexed(filename).get(str(key), {})
        value = obj.get(field, fallback) if isinstance(obj, dict) else fallback
        if value is None:
            return ""
        if isinstance(value, str):
            return value
        return json.dumps(value, ensure_ascii=False, separators=(",", ":"))

    def checklist_target(self, row: dict[str, str]) -> tuple[str, str, str] | None:
        filename = Path(row["file"]).name
        if filename not in {p.name for p in self.folder.glob("*.json")}:
            return None
        data = self.load(filename)
        raw = row["key_or_line"]
        parts = [x for x in raw.split("/") if x]
        if not parts:
            return None
        if isinstance(data, list) and raw.startswith("/") and parts[0].isdigit():
            index = int(parts[0])
            if index >= len(data) or not isinstance(data[index], dict):
                return None
            key = stable_key(Path(filename).stem, data[index])
        else:
            key = parts[0]
        return filename, key, row["field"]


