    index: dict[tuple[str, str, str], dict[str, str]] = {}
    for row in master:
        if row["scope"] != "runtime_dictionary":
            continue
        key = (Path(row["file"]).name, row["stable_key_or_line"], row["field"])
        if key in index:
            raise AssertionError(f"duplicate runtime review target: {key}")
        index[key] = row

    applied: list[dict[str, str]] = []
    for correction in read_tsv(PASS18):
        filename = Path(correction["file"]).name
        target = (filename, correction["stable_key"], correction["field"])
        is_static = not correction["file"].startswith("magica/js/libs/")

        if is_static:
            product_path = PRODUCT / correction["file"]
            text = product_path.read_text(encoding="utf-8-sig")
