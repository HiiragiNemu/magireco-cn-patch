def build_glossary_support_and_frontend_backlog() -> tuple[list[dict[str, str]], list[dict[str, str]]]:
    """Return the Wiki glossary support layer and audited empty frontend rows.

    The glossary is authority evidence rather than an additional product-text
    review universe, so it is intentionally kept outside the master inventory.
    Empty frontend candidates are classified by the closed exact-node audit, not
    inferred from an empty offline maintenance field.
    """

    provenance_path = PRODUCT / "i18n" / "generated" / "input-provenance.tsv"
    provenance = read_tsv(provenance_path)
    glossary_rows: list[dict[str, str]] = []
    frontend_backlog: list[dict[str, str]] = []
    for source in provenance:
        source_file = source["source_file"]
        if source_file == "i18n/glossary.tsv":
            glossary_rows.append(
                {
                    "support_id": "",
                    "japanese_or_source_original": source["source_text"],
                    "authority_cn": source["candidate_cn"],
                    "authority_tier": "2_wiki",
                    "source_batch": source["source_batch"],
                    "source_author": "HiiragiNemu/magireco-wiki-data contributors",
                    "confidence": "high_as_wiki_candidate",
                    "runtime_consumed": "false; offline authority input, not directly consumed at runtime",
                    "manual_review_status": "authority-support-available",
                    "evidence": (
                        f"{relative_display(provenance_path)}:{source['source_line']};"
                        f"{source['evidence']};key={source['key']}"
                    ),
                    "notes": "Wiki is second authority; official CN still wins on an exact stable-ID conflict",
                }
            )
        elif source_file == "i18n/frontend-strings.tsv" and source["key"] in FRONTEND_EMPTY_53_DECISIONS:
            frontend_backlog.append(
                {
                    "backlog_id": "",
                    "file": source_file,
                    "stable_key_or_line": source["key"],
                    "scope": source["scope"],
                    "path_prefix": source["path_prefix"],
                    "japanese_or_source_original": source["source_text"],
                    "missing_original_reason": (
                        "extracted source string is retained; exact-node semantics are separately audited"
                    ),
                    "source_batch": source["source_batch"],
                    "evidence": (
                        f"{relative_display(provenance_path)}:{source['source_line']};"
                        f"{source['evidence']};candidate_id={source['candidate_id']};key={source['key']};"
                        "semantic_audit_sha256=a8d66dcdec688e4baa14071950764802ef696e0d6ea6133ab5709e5dff4c4959;"
                        "closure_items_sha256=5388304f6acf4a610303e335eda6b1e598e6842ded901b1a502f39d2aa05bfe3"
                    ),
                    **classify_frontend_empty_candidate(source),
                }
            )

    glossary_rows.sort(key=lambda r: (r["japanese_or_source_original"], r["authority_cn"]))
    frontend_backlog.sort(key=lambda r: (r["path_prefix"], r["japanese_or_source_original"]))
    for idx, row in enumerate(glossary_rows, 1):
        row["support_id"] = f"WGS-{idx:04d}"
    for idx, row in enumerate(frontend_backlog, 1):
        row["backlog_id"] = f"FUT-{idx:03d}"
    return glossary_rows, frontend_backlog


